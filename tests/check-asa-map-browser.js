// ARK Survival Ascended map-specific nested folders regression test.
// Run with: node tests/check-asa-map-browser.js
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assets=path.resolve(__dirname,'../app/src/main/assets');
const html=fs.readFileSync(path.join(assets,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map(x=>x[1]);
assert(scripts.includes('asa-map-browser.js'),'Map browser not loaded by Android HTML');
const content=Object.fromEntries(scripts.map(file=>[file,fs.readFileSync(path.join(assets,file),'utf8')]));
const memory=new Map([['genesis.gameNotes.v1',JSON.stringify({'ASA::Ragnarok':[{
id:'legacy',title:'Old Ragnarok note',body:'Must persist',updatedAt:'2026-10-01',createdAt:'2026-10-01',type:'personal'
}]})]]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k),key:i=>[...memory.keys()][i],get length(){return memory.size}};
const nodes={screen:{innerHTML:''},toast:{textContent:'',classList:{add(){},remove(){}}},gameNoteTitle:{value:'Bison observation'},gameNoteBody:{value:'Bison near river: needs confirmation'},gameNoteSource:{value:''}};
const doc={getElementById:k=>nodes[k]||(nodes[k]={innerHTML:'',value:''}),querySelectorAll:()=>[],body:{style:{setProperty(){}}}};
const ctx=vm.createContext({window:{},document:doc,localStorage:storage,scrollTo(){},setTimeout(){},URL,confirm:()=>true,console});
for(const name of scripts)vm.runInContext(content[name],ctx,{filename:name});
const inline=html.slice(html.lastIndexOf('<script>')+8,html.indexOf('</script>',html.lastIndexOf('<script>')));
vm.runInContext(inline,ctx,{filename:'index.html'});
const run=(js)=>vm.runInContext(js,ctx);
assert.equal(run('asaMaps.length'),10,'Ten map workspaces required');
assert.equal(run("asaMapFacts('ragnarok').length"),96,'Original Ragnarok reference facts lost');
assert.equal(run("asaMapFacts('the-island').length"),0,'Ragnarok facts may not leak into another map');
run("selectGame('ASA');selectGameFolder('Maps')");
assert(run('gamePage()').includes('Ragnarok'),'Map list missing Ragnarok');
run("asaSearchFolders('ragnarok')");
assert.equal(run('asaBrowserItemsFiltered().length'),1,'Search should show one Ragnarok card');
run("asaSearchFolders('');asaChangeFilter('references')");
assert.equal(run('asaBrowserItemsFiltered().length'),1,'Only Ragnarok has populated sources');
run("asaChangeFilter('all');asaChangeSort('most-facts')");
assert.equal(run('asaBrowserItemsFiltered()[0].id'),'ragnarok','Sort must prioritize populated reference map');
run("asaSelectMap('ragnarok')");
assert.equal(run('asaBrowserLevel()'),1);
assert(run('gamePage()').includes('Creatures &amp; Taming'),'Map category not accessible');
run("asaSelectCategory('creatures')");
assert.equal(run('asaBrowserLevel()'),2);
assert(run('gamePage()').includes('Bison'),'Map subfolder missing');
run("asaSelectSubfolder('bison')");
assert.equal(run('asaBrowserLevel()'),3);
assert(run('gamePage()').includes('MAP REFERENCE ENTRIES'),'Bison references missing');
assert.equal(run('currentGameFolderKey()'),'ASA::map::ragnarok::creatures::bison');
run('beginGameNote();saveGameNote()');
assert.equal(run("gameNotesRead()['ASA::map::ragnarok::creatures::bison'].length"),1,'New map note not saved');
assert.equal(run("gameNotesRead()['ASA::Ragnarok'].length"),1,'Legacy Ragnarok note must be preserved');
assert(run('gamePage()').includes('Search saved notes'),'Note search UI missing');
assert(run('gamePage()').includes('Sort notes'),'Note sort UI missing');
run("asaJump(0);asaSelectMap('the-island');asaSelectCategory('creatures');asaSelectSubfolder('bison')");
assert.equal(run('currentGameFolderKey()'),'ASA::map::the-island::creatures::bison');
assert(!run('gamePage()').includes('Bison observation'),'Other map showed Ragnarok note');
assert(run('gamePage()').includes('no sourced records yet'),'Other map should not pretend to have proven sources');
run("beginGameNote()");
nodes.gameNoteTitle.value='Island discovery';nodes.gameNoteBody.value='Unique to island';
run('saveGameNote()');
assert.equal(run("gameNotesRead()['ASA::map::the-island::creatures::bison'].length"),1,'Other-map note not saved');
assert.equal(run("gameNotesRead()['ASA::map::ragnarok::creatures::bison'].length"),1,'Ragnarok note overwritten');
run('asaBack()');
assert.equal(run('asaBrowserLevel()'),2,'Back button failed to return one folder level');
run('asaBack()');
assert.equal(run('asaBrowserLevel()'),1,'Back button failed category traversal');
run('asaBack()');
assert.equal(run('asaBrowserLevel()'),0,'Back button failed to return to maps');
assert(scripts.every(name=>!!content[name]),'Android assets missing in source');
console.log('PASS: 10 maps, nested folders, filter, sort, source isolation, note persistence, legacy access, back navigation');
